-- JRDB PWA independent index base schema v0.1
-- Purpose: time-aware longitudinal source layer for RunPerf / Ability / Edge research.
-- This database is intentionally separate from Analysis Lite / Stats Mart / PWA Fact Lite.

CREATE TABLE meta_index_base_build(
  build_id INTEGER PRIMARY KEY,
  builder_version TEXT NOT NULL,
  schema_version TEXT NOT NULL,
  started_at TEXT NOT NULL,
  finished_at TEXT,
  status TEXT NOT NULL,
  years_json TEXT NOT NULL,
  source_manifest_json TEXT,
  race_count INTEGER,
  race_result_context_count INTEGER,
  runner_pre_count INTEGER,
  runner_result_count INTEGER,
  workout_count INTEGER,
  training_count INTEGER,
  profile_observation_count INTEGER,
  anomaly_count INTEGER,
  message TEXT
);

CREATE TABLE meta_index_base_source(
  source_id INTEGER PRIMARY KEY,
  build_id INTEGER NOT NULL,
  source_kind TEXT NOT NULL,
  year INTEGER NOT NULL,
  archive_path TEXT NOT NULL,
  archive_sha256 TEXT,
  archive_size_bytes INTEGER,
  member_count INTEGER,
  imported_at TEXT NOT NULL,
  FOREIGN KEY(build_id) REFERENCES meta_index_base_build(build_id)
);

CREATE TABLE meta_index_base_anomaly(
  anomaly_id INTEGER PRIMARY KEY,
  build_id INTEGER NOT NULL,
  severity TEXT NOT NULL,
  anomaly_type TEXT NOT NULL,
  source_kind TEXT,
  year INTEGER,
  business_key TEXT,
  detail TEXT,
  detected_at TEXT NOT NULL,
  FOREIGN KEY(build_id) REFERENCES meta_index_base_build(build_id)
);

CREATE TABLE race_context(
  race_key TEXT PRIMARY KEY,
  race_date TEXT NOT NULL,
  year INTEGER NOT NULL,
  venue_code TEXT NOT NULL,
  race_no INTEGER NOT NULL,
  start_time TEXT,
  distance_m INTEGER,
  surface_code TEXT,
  turn_code TEXT,
  inner_outer_code TEXT,
  race_type_code TEXT,
  race_condition_code TEXT,
  race_symbol_code TEXT,
  weight_condition_code TEXT,
  grade_code TEXT,
  race_name TEXT,
  declared_field_size INTEGER,
  course_code TEXT,
  meeting_area_code TEXT,
  availability_class TEXT NOT NULL CHECK(availability_class IN ('PRE_RACE','CURRENT_RESULT_FALLBACK')),
  source_kind TEXT NOT NULL,
  source_member TEXT,
  record_hash TEXT NOT NULL
);

CREATE TABLE race_result_context(
  race_key TEXT PRIMARY KEY,
  track_condition_code TEXT,
  weather_code TEXT,
  source_member TEXT,
  semantic_hash TEXT NOT NULL,
  FOREIGN KEY(race_key) REFERENCES race_context(race_key)
);


CREATE VIEW v_runner_longitudinal_base AS
SELECT
  r.race_date,
  r.year,
  r.venue_code,
  r.race_no,
  r.race_key,
  r.start_time,
  r.distance_m,
  r.surface_code,
  r.turn_code,
  r.inner_outer_code,
  r.race_type_code,
  r.race_condition_code,
  r.race_symbol_code,
  r.weight_condition_code,
  r.grade_code,
  r.race_name,
  r.declared_field_size,
  r.course_code,
  r.availability_class AS race_context_availability,
  rc.track_condition_code,
  rc.weather_code,
  p.horse_no,
  p.frame_no,
  p.horse_id,
  p.horse_name,
  p.sex_code,
  p.jockey_name AS pre_jockey_name,
  p.jockey_code AS pre_jockey_code,
  p.trainer_name AS pre_trainer_name,
  p.trainer_code AS pre_trainer_code,
  p.carried_weight_kg AS pre_carried_weight_kg,
  p.running_style_code AS pre_running_style_code,
  p.distance_aptitude_code,
  p.uptrend_code,
  p.rotation_interval,
  p.pre_idm,
  p.training_score,
  p.stable_score,
  p.training_arrow_code,
  p.stable_evaluation_code,
  p.blinker_code,
  p.condition_class_code,
  p.body_weight_pre_kg,
  p.body_weight_change_pre_kg,
  p.start_index,
  p.slow_start_rate,
  p.stable_run_no,
  p.stable_entry_date,
  p.stable_days_before,
  x.result_key,
  x.finish,
  x.abnormal_code,
  x.time_sec,
  x.idm,
  x.raw_score,
  x.first3f_sec,
  x.last3f_sec,
  x.corner1,
  x.corner2,
  x.corner3,
  x.corner4,
  x.body_weight_kg,
  x.body_weight_change_kg,
  x.final_win_odds,
  x.final_win_popularity,
  x.win_payout,
  x.place_payout,
  w.training_date,
  w.course_code AS workout_course_code,
  w.effort_code,
  w.chase_state_code,
  w.rider_type_code,
  w.furlong_count,
  w.first_segment_sec,
  w.middle_segment_sec,
  w.final_segment_sec,
  w.jrdb_workout_index,
  t.training_type_code,
  t.training_course_type_code,
  t.finish_index,
  t.training_volume_code,
  t.finish_change_code,
  t.training_evaluation_code,
  t.week_ago_workout_index
FROM race_context r
LEFT JOIN race_result_context rc ON rc.race_key = r.race_key
JOIN runner_pre p ON p.race_key = r.race_key
LEFT JOIN runner_result x ON x.race_key = p.race_key AND x.horse_no = p.horse_no
LEFT JOIN workout_main w ON w.race_key = p.race_key AND w.horse_no = p.horse_no
LEFT JOIN training_analysis t ON t.race_key = p.race_key AND t.horse_no = p.horse_no;

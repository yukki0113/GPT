CREATE TABLE course_stats (
  stats_id TEXT PRIMARY KEY,
  course_key TEXT NOT NULL,
  period_from TEXT NOT NULL,
  period_to_exclusive TEXT NOT NULL,
  stats_definition_version TEXT NOT NULL,
  source_generation TEXT NOT NULL,
  generated_at TEXT NOT NULL,

  sample_race_count INTEGER NOT NULL,
  sample_runner_count INTEGER NOT NULL,
  overall_top3_rate REAL,

  race_first3f_sample_count INTEGER NOT NULL,
  avg_race_first3f_sec REAL,
  race_time_sample_count INTEGER NOT NULL,
  avg_winner_time_sec REAL,
  avg_winner_last3f_sec REAL,
  avg_winner_position_4c REAL,
  avg_top3_position_4c REAL,

  race_pace_index_sample_count INTEGER NOT NULL,
  avg_race_pace_index REAL,
  race_pace_code_sample_count INTEGER NOT NULL,
  high_pace_rate REAL,
  middle_pace_rate REAL,
  slow_pace_rate REAL,

  front_runner_count INTEGER NOT NULL,
  front_win_rate REAL,
  front_top3_rate REAL,
  stalker_runner_count INTEGER NOT NULL,
  stalker_win_rate REAL,
  stalker_top3_rate REAL,
  midpack_runner_count INTEGER NOT NULL,
  midpack_win_rate REAL,
  midpack_top3_rate REAL,
  closer_runner_count INTEGER NOT NULL,
  closer_win_rate REAL,
  closer_top3_rate REAL,

  last3f_sample_runner_count INTEGER NOT NULL,
  avg_top3_last3f_sec REAL,
  avg_winner_last3f_percentile REAL,
  avg_top3_last3f_percentile REAL,
  avg_all_last3f_percentile REAL,
  late_speed_importance_delta REAL,

  draw_sample_runner_count INTEGER NOT NULL,
  inside_draw_win_rate REAL,
  inside_draw_top3_rate REAL,
  middle_draw_win_rate REAL,
  middle_draw_top3_rate REAL,
  outside_draw_win_rate REAL,
  outside_draw_top3_rate REAL,
  inside_draw_advantage REAL,
  outside_draw_advantage REAL,

  UNIQUE(course_key, period_from, period_to_exclusive, stats_definition_version)
);

